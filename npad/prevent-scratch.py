#!/usr/bin/env python3

import argparse
import fcntl
import json
import os
import re
import shlex
import stat
import subprocess
import sys
import tempfile
from pathlib import Path


BEGIN_MARKER = "// BEGIN NPAD PREVENT SELECTING SCRATCH"
END_MARKER = "// END NPAD PREVENT SELECTING SCRATCH"
GENERATED_MARKER = "// Generated by npad. Do not edit."
TARGET_ACTIONS = {
    "focus-workspace-up",
    "focus-workspace-down",
    "focus-window-or-workspace-up",
    "focus-window-or-workspace-down",
}


class ConfigError(Exception):
    pass


def mask_comments(text):
    chars = list(text)
    index = 0
    in_string = False
    escaped = False
    while index < len(text):
        char = text[index]
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            index += 1
            continue
        if char == '"':
            in_string = True
            index += 1
            continue
        if text.startswith("//", index):
            end = text.find("\n", index)
            end = len(text) if end < 0 else end
            for position in range(index, end):
                chars[position] = " "
            index = end
            continue
        if text.startswith("/*", index):
            end = text.find("*/", index + 2)
            if end < 0:
                raise ConfigError("Unterminated block comment in Niri config.")
            for position in range(index, end + 2):
                if chars[position] != "\n":
                    chars[position] = " "
            index = end + 2
            continue
        index += 1
    return "".join(chars)


def mask_strings(text):
    chars = list(text)
    index = 0
    in_string = False
    escaped = False
    while index < len(text):
        char = text[index]
        if in_string:
            if char != "\n":
                chars[index] = " "
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
            chars[index] = " "
        index += 1
    return "".join(chars)


def matching_brace(text, opening):
    depth = 0
    for index in range(opening, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return index
    raise ConfigError("Unmatched brace in Niri config.")


def binding_nodes(source):
    uncommented = mask_comments(source)
    code = mask_strings(uncommented)
    blocks = []
    for match in re.finditer(r"(?m)^[ \t]*binds[ \t]*\{", code):
        opening = code.find("{", match.start(), match.end())
        closing = matching_brace(code, opening)
        cursor = opening + 1
        while cursor < closing:
            node_open = code.find("{", cursor, closing)
            if node_open < 0:
                break
            node_close = matching_brace(code, node_open)
            if node_close >= closing:
                raise ConfigError("Malformed key binding block in Niri config.")
            header = mask_comments(source[cursor:node_open]).strip().strip(";").strip()
            body = source[node_open + 1:node_close]
            if header and not header.startswith("/-"):
                chord_match = re.match(r"(\S+)", header)
                if chord_match:
                    blocks.append((cursor, chord_match.group(1), header, body))
            cursor = node_close + 1
    return blocks


def include_events(source):
    uncommented = mask_comments(source)
    pattern = re.compile(
        r'(?m)^[ \t]*include(?:[ \t]+(optional=true))?[ \t]+("(?:\\.|[^"\\])*")'
    )
    events = []
    for match in pattern.finditer(uncommented):
        try:
            include_path = json.loads(match.group(2))
        except json.JSONDecodeError as error:
            raise ConfigError(f"Invalid Niri include path: {error}") from error
        events.append((match.start(), include_path, match.group(1) == "optional=true"))
    return events


def target_action_matches(body):
    code = mask_strings(mask_comments(body))
    pattern = re.compile(
        r"\b(" + "|".join(sorted(TARGET_ACTIONS)) + r")\b(?=\s*(?:;|}))"
    )
    return list(pattern.finditer(code))


def path_from_include(value, including_file):
    path = Path(os.path.expandvars(os.path.expanduser(value)))
    if not path.is_absolute():
        path = including_file.parent / path
    return path.resolve()


def collect_bindings(config_path, generated_path):
    bindings = {}
    visited = set()
    generated_path = generated_path.resolve()

    def visit(path, root=False):
        path = path.resolve()
        if path == generated_path:
            raise ConfigError(
                f"{generated_path} is already included outside npad's managed block."
            )
        if path in visited:
            return
        visited.add(path)
        try:
            source = path.read_text(encoding="utf-8")
        except OSError as error:
            raise ConfigError(f"Could not read Niri config {path}: {error}") from error
        if root:
            source, _ = remove_managed_block(source)

        binding_events = [
            (position, "binding", (chord, header, body))
            for position, chord, header, body in binding_nodes(source)
        ]
        include_events_in_file = [
            (position, "include", (include_path, optional))
            for position, include_path, optional in include_events(source)
        ]
        for _, event_type, payload in sorted(binding_events + include_events_in_file):
            if event_type == "include":
                include_path, optional = payload
                included_path = path_from_include(include_path, path)
                if included_path == generated_path:
                    raise ConfigError(
                        f"{generated_path} is already included outside npad's managed block."
                    )
                if not included_path.exists():
                    if optional:
                        continue
                    raise ConfigError(f"Niri include does not exist: {included_path}")
                visit(included_path)
            else:
                chord, header, body = payload
                bindings[chord] = (header, body)

    visit(config_path, root=True)
    return bindings


def generated_config(config_path, plugin_dir, scratch_workspace):
    override_path = config_path.parent / "npad.kdl"
    bindings = collect_bindings(config_path, override_path)
    replacements = []
    for header, body in bindings.values():
        matches = target_action_matches(body)
        if not matches:
            continue
        replaced_body = body
        for match in reversed(matches):
            action = match.group(1)
            command = " ".join(
                shlex.quote(part)
                for part in (
                    "bash",
                    str(Path(plugin_dir) / "prevent-scratch.sh"),
                    "navigate",
                    action,
                    scratch_workspace,
                )
            )
            replaced_body = (
                replaced_body[:match.start()]
                + "spawn-sh "
                + json.dumps(command)
                + replaced_body[match.end():]
            )
        replacements.append(f"    {header} {{{replaced_body}}}")

    if not replacements:
        raise ConfigError(
            "No active focus-workspace-up/down or "
            "focus-window-or-workspace-up/down bindings were found."
        )
    return (
        f"{GENERATED_MARKER}\n"
        "// The original bindings and their options are preserved.\n"
        "binds {\n"
        + "\n".join(replacements)
        + "\n}\n"
    )


def managed_block(include_path, newline="\n"):
    include = json.dumps(include_path, ensure_ascii=False)
    return newline.join((BEGIN_MARKER, f"include {include}", END_MARKER)) + newline


def update_managed_block(source, include_path):
    pattern = re.compile(
        rf"(?ms)^{re.escape(BEGIN_MARKER)}\r?\n.*?^{re.escape(END_MARKER)}(?:\r?\n|$)"
    )
    matches = list(pattern.finditer(source))
    if len(matches) > 1:
        raise ConfigError("Multiple npad-managed include blocks found in Niri config.")
    newline = "\r\n" if "\r\n" in source else "\n"
    replacement = managed_block(include_path, newline)
    if matches:
        match = matches[0]
        return source[:match.start()] + replacement + source[match.end():]
    separator = "" if not source or source.endswith(("\n", "\r")) else newline
    return source + separator + replacement


def remove_managed_block(source):
    pattern = re.compile(
        rf"(?ms)^{re.escape(BEGIN_MARKER)}\r?\n.*?^{re.escape(END_MARKER)}(?:\r?\n|$)"
    )
    updated, count = pattern.subn("", source)
    if count > 1:
        raise ConfigError("Multiple npad-managed include blocks found in Niri config.")
    return updated, count > 0


def atomic_write(path, contents, mode=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.npad-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as temporary:
            temporary.write(contents)
            temporary.flush()
            os.fsync(temporary.fileno())
        if mode is not None:
            os.chmod(temporary_name, mode)
        os.replace(temporary_name, path)
    finally:
        try:
            os.unlink(temporary_name)
        except OSError:
            pass


def validate_candidate(config_path, config_contents, generated_contents):
    override_fd, override_name = tempfile.mkstemp(
        prefix=".npad-validate-", suffix=".kdl", dir=config_path.parent
    )
    config_fd, config_name = tempfile.mkstemp(
        prefix=".npad-config-validate-", suffix=".kdl", dir=config_path.parent
    )
    try:
        with os.fdopen(override_fd, "w", encoding="utf-8") as override:
            override.write(generated_contents)
        config_contents = update_managed_block(config_contents, override_name)
        with os.fdopen(config_fd, "w", encoding="utf-8") as config:
            config.write(config_contents)
        result = subprocess.run(
            ["niri", "validate", "--config", config_name],
            capture_output=True,
            text=True,
            timeout=15,
            check=False,
        )
        if result.returncode != 0:
            detail = result.stderr.strip() or result.stdout.strip() or f"exit status {result.returncode}"
            raise ConfigError(f"Niri rejected the generated keybindings: {detail}")
    except OSError as error:
        raise ConfigError(f"Could not validate the Niri config: {error}") from error
    except subprocess.TimeoutExpired as error:
        raise ConfigError("Niri config validation timed out.") from error
    finally:
        for temporary_path in (override_name, config_name):
            try:
                os.unlink(temporary_path)
            except OSError:
                pass


def remove_generated_file(path):
    if not path.exists():
        return
    try:
        contents = path.read_text(encoding="utf-8")
    except OSError as error:
        raise ConfigError(f"Could not inspect generated Niri config {path}: {error}") from error
    if not contents.startswith(GENERATED_MARKER + "\n"):
        return
    try:
        path.unlink()
    except OSError as error:
        raise ConfigError(f"Could not remove generated Niri config {path}: {error}") from error


def config_includes_path(config_path, target_path, visited=None):
    visited = set() if visited is None else visited
    config_path = Path(config_path).resolve()
    target_path = Path(target_path).resolve()
    if config_path in visited or not config_path.is_file():
        return False
    visited.add(config_path)
    try:
        source = config_path.read_text(encoding="utf-8")
    except OSError as error:
        raise ConfigError(f"Could not read Niri config {config_path}: {error}") from error
    source, _ = remove_managed_block(source)
    for _, include_path, optional in include_events(source):
        included_path = path_from_include(include_path, config_path)
        if included_path == target_path:
            return True
        if not included_path.exists():
            if optional:
                continue
            continue
        if config_includes_path(included_path, target_path, visited):
            return True
    return False


def cleanup_config(path, remove_generated=True):
    if not path:
        return
    config_path = Path(path)
    try:
        source = config_path.read_text(encoding="utf-8")
    except FileNotFoundError:
        source = None
    except OSError as error:
        raise ConfigError(f"Could not read Niri config {config_path}: {error}") from error
    if source is not None:
        updated, changed = remove_managed_block(source)
        if changed:
            atomic_write(config_path, updated, stat.S_IMODE(config_path.stat().st_mode))
    if remove_generated:
        generated_path = config_path.parent / "npad.kdl"
        if source is None or not config_includes_path(config_path, generated_path):
            remove_generated_file(generated_path)


def resolve_config_path(value):
    if value.strip():
        path = Path(os.path.expandvars(os.path.expanduser(value.strip())))
    elif os.environ.get("NIRI_CONFIG"):
        path = Path(os.path.expandvars(os.path.expanduser(os.environ["NIRI_CONFIG"])))
    elif os.environ.get("XDG_CONFIG_HOME", "").startswith("/"):
        path = Path(os.environ["XDG_CONFIG_HOME"]) / "niri" / "config.kdl"
    else:
        path = Path.home() / ".config" / "niri" / "config.kdl"
    if not path.is_absolute():
        path = Path.cwd() / path
    return path.resolve()


def sync_configuration(config_value, state_dir, plugin_dir, scratch_workspace, enabled):
    data_dir = Path(state_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    lock_path = data_dir / "prevent-scratch.lock"
    with lock_path.open("w", encoding="utf-8") as lock_file:
        fcntl.flock(lock_file, fcntl.LOCK_EX)
        state_path = data_dir / "prevent-scratch.json"
        state = {}
        if state_path.exists():
            try:
                state = json.loads(state_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError) as error:
                raise ConfigError(f"Could not read npad config state: {error}") from error
        previous_config = state.get("config_path")
        current_config = resolve_config_path(config_value)

        if not enabled:
            configs = {str(current_config)}
            if previous_config:
                configs.add(str(Path(previous_config)))
            for path in configs:
                cleanup_config(path, remove_generated=False)
            for directory in {Path(path).parent for path in configs}:
                generated_path = directory / "npad.kdl"
                if not any(
                    config_includes_path(Path(config), generated_path)
                    for config in configs
                ):
                    remove_generated_file(generated_path)
            try:
                state_path.unlink()
            except FileNotFoundError:
                pass
            return

        if not current_config.is_file():
            raise ConfigError(f"Niri config file does not exist: {current_config}")
        override_path = current_config.parent / "npad.kdl"
        original_config = current_config.read_text(encoding="utf-8")
        unmanaged_config, _ = remove_managed_block(original_config)
        if any(
            path_from_include(include_path, current_config) == override_path.resolve()
            for _, include_path, _ in include_events(unmanaged_config)
        ):
            raise ConfigError(
                f"{override_path} is already included outside npad's managed block."
            )
        if override_path.exists():
            existing = override_path.read_text(encoding="utf-8")
            if not existing.startswith(GENERATED_MARKER + "\n"):
                raise ConfigError(
                    f"{override_path} already exists and is not managed by npad; "
                    "rename it or choose another config directory."
                )
        generated = generated_config(current_config, plugin_dir, scratch_workspace)
        generated = generated_config(current_config, plugin_dir, scratch_workspace)
        include_path = "./npad.kdl"
        updated_config = update_managed_block(original_config, include_path)
        validate_candidate(current_config, updated_config, generated)

        config_mode = stat.S_IMODE(current_config.stat().st_mode)
        atomic_write(override_path, generated, 0o600)
        if updated_config != original_config:
            atomic_write(current_config, updated_config, config_mode)

        if previous_config and Path(previous_config) != current_config:
            cleanup_config(
                previous_config,
                remove_generated=(Path(previous_config).parent / "npad.kdl").resolve()
                != override_path.resolve(),
            )
        atomic_write(
            state_path,
            json.dumps({"config_path": str(current_config)}, indent=2) + "\n",
            0o600,
        )


def run_niri(arguments):
    try:
        result = subprocess.run(
            ["niri", "msg", *arguments],
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise ConfigError(f"Could not run niri: {error}") from error
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip() or f"exit status {result.returncode}"
        raise ConfigError(f"Niri command failed: {detail}")
    return result.stdout


def run_niri_json(arguments, label):
    try:
        return json.loads(run_niri(["--json", *arguments]))
    except json.JSONDecodeError as error:
        raise ConfigError(f"Could not parse Niri {label} response: {error}") from error


def focus_window_id(windows):
    if not isinstance(windows, list):
        raise ConfigError("Niri returned an invalid windows response.")
    focused = next(
        (
            window for window in windows
            if isinstance(window, dict) and window.get("is_focused") is True
        ),
        None,
    )
    return focused.get("id") if focused else None


def navigate(action, scratch_workspace):
    direction = -1 if action.endswith("-up") else 1
    if action.startswith("focus-window-or-workspace-"):
        before_windows = run_niri_json(["windows"], "windows")
        before_id = focus_window_id(before_windows)
        run_niri(["action", "focus-window-" + ("up" if direction < 0 else "down")])
        after_windows = run_niri_json(["windows"], "windows")
        after_id = focus_window_id(after_windows)
        if after_id is not None and after_id != before_id:
            return
        windows = after_windows
    else:
        windows = run_niri_json(["windows"], "windows")

    workspaces = run_niri_json(["workspaces"], "workspaces")
    if not isinstance(workspaces, list):
        raise ConfigError("Niri returned an invalid workspaces response.")
    focused_window = next(
        (
            window for window in windows
            if isinstance(window, dict) and window.get("is_focused") is True
        ),
        None,
    )
    focused_workspace = next(
        (
            workspace for workspace in workspaces
            if isinstance(workspace, dict) and workspace.get("is_focused") is True
        ),
        None,
    )
    if focused_workspace is None and focused_window is not None:
        workspace_id = focused_window.get("workspace_id")
        focused_workspace = next(
            (
                workspace for workspace in workspaces
                if isinstance(workspace, dict) and workspace.get("id") == workspace_id
            ),
            None,
        )
    if focused_workspace is None:
        focused_workspace = next(
            (
                workspace for workspace in workspaces
                if isinstance(workspace, dict) and workspace.get("is_active") is True
            ),
            None,
        )
    if focused_workspace is None:
        raise ConfigError("Niri did not report the focused workspace.")

    output = focused_workspace.get("output")
    ordered = sorted(
        (
            workspace
            for workspace in workspaces
            if isinstance(workspace, dict)
            and workspace.get("output") == output
            and isinstance(workspace.get("idx"), int)
        ),
        key=lambda workspace: workspace["idx"],
    )
    current_position = next(
        (index for index, workspace in enumerate(ordered) if workspace.get("id") == focused_workspace.get("id")),
        None,
    )
    if current_position is None:
        raise ConfigError("Could not locate the focused workspace in Niri's workspace list.")

    target_position = current_position + direction
    while 0 <= target_position < len(ordered):
        candidate = ordered[target_position]
        if candidate.get("name") != scratch_workspace:
            run_niri(["action", "focus-workspace", str(candidate["idx"])])
            return
        target_position += direction


def notify_panel_error(message):
    try:
        result = subprocess.run(
            [
                "noctalia",
                "msg",
                "plugin",
                "ffngs/npad:manager",
                "all",
                "prevent-scratch-error",
                message,
            ],
            capture_output=True,
            text=True,
            timeout=3,
            check=False,
        )
        if result.returncode != 0:
            detail = result.stderr.strip() or f"exit status {result.returncode}"
            print(f"{message} (could not notify the npad panel: {detail})", file=sys.stderr)
    except (OSError, subprocess.TimeoutExpired):
        print(message, file=sys.stderr)


def main():
    parser = argparse.ArgumentParser()
    subparsers = parser.add_subparsers(dest="command", required=True)
    configure_parser = subparsers.add_parser("configure")
    configure_parser.add_argument("config_path")
    configure_parser.add_argument("state_dir")
    configure_parser.add_argument("plugin_dir")
    configure_parser.add_argument("scratch_workspace")
    configure_parser.add_argument("enabled", choices=("true", "false"))
    navigate_parser = subparsers.add_parser("navigate")
    navigate_parser.add_argument("action", choices=sorted(TARGET_ACTIONS))
    navigate_parser.add_argument("scratch_workspace")
    args = parser.parse_args()

    try:
        if args.command == "configure":
            sync_configuration(
                args.config_path,
                args.state_dir,
                args.plugin_dir,
                args.scratch_workspace,
                args.enabled == "true",
            )
        else:
            navigate(args.action, args.scratch_workspace)
    except ConfigError as error:
        if args.command == "navigate":
            notify_panel_error(str(error))
        else:
            print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
